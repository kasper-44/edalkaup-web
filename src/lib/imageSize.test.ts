import assert from 'node:assert/strict'
import { parseImageSize } from '@/lib/imageSize'

const png = new Uint8Array([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
  0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
  0x00, 0x00, 0x04, 0x00,
  0x00, 0x00, 0x03, 0x00,
])
assert.deepEqual(parseImageSize(png), { width: 1024, height: 768 })

const jpeg = new Uint8Array([
  0xff, 0xd8,
  0xff, 0xe0, 0x00, 0x04, 0x00, 0x00,
  0xff, 0xc0, 0x00, 0x11, 0x08,
  0x04, 0x38,
  0x07, 0x80,
])
assert.deepEqual(parseImageSize(jpeg), { width: 1920, height: 1080 })
assert.equal(parseImageSize(new Uint8Array([1, 2, 3])), null)

console.log('image size tests passed')
